#!/usr/bin/env python3
"""Generate a 1-bit bitmap font subset from a TrueType/OpenType font.

Produces two files: main/<name>.c and main/<name>.h, using the glyph table
format from main/glyphfont.h. Only the characters that are actually used are
emitted, which keeps the tables small enough for the ESP32 flash.

Usage:
    python3 tools/gen_glyphfont.py --name font_text --size 24 \
        --chars-file tools/fonts/text_gb2312.txt

    python3 tools/gen_glyphfont.py --name font_status --size 16 \
        --chars-file tools/fonts/status_chars.txt
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_TTF = os.path.join(HERE, "fonts", "wqy-zenhei.ttc")

ap = argparse.ArgumentParser()
ap.add_argument("--name", required=True, help="output file stem, e.g. font_text")
ap.add_argument("--ttf", default=DEFAULT_TTF)
ap.add_argument("--size", type=int, required=True, help="pixel size")
ap.add_argument("--chars")
ap.add_argument("--chars-file")
ap.add_argument("--threshold", type=int, default=110,
                help="luminance threshold for 1-bit conversion (lower = bolder)")
ap.add_argument("--font-index", type=int, default=0, help="index inside a .ttc")
ap.add_argument("--outdir", default=os.path.join(ROOT, "main"))
args = ap.parse_args()

if not args.chars and not args.chars_file:
    raise SystemExit("need --chars or --chars-file")

if args.chars_file:
    with open(args.chars_file, encoding="utf-8") as f:
        # Keep the space character: only line breaks are dropped.
        chars = "".join(f.read().splitlines())
else:
    chars = args.chars

# Unique, sorted code points
wanted = sorted({ord(c) for c in chars})

font = ImageFont.truetype(args.ttf, args.size, index=args.font_index)
ascent, descent = font.getmetrics()
cell_h = ascent + descent + 1

glyphs = []   # (cp, width, advance, row_bytes, rows, bytes)
data = bytearray()

for cp in wanted:
    ch = chr(cp)
    advance = max(1, int(round(font.getlength(ch))))
    img = Image.new("L", (advance, cell_h), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0, ascent), ch, font=font, fill=255, anchor="ls")

    px = img.load()
    row_bytes = (advance + 7) // 8
    body = bytearray()
    for y in range(cell_h):
        for b in range(row_bytes):
            value = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < advance and px[x, y] >= args.threshold:
                    value |= 0x80 >> bit
            body.append(value)

    glyphs.append((cp, advance, advance, row_bytes, cell_h, len(data)))
    data.extend(body)

# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------

stem = args.name
c_path = os.path.join(args.outdir, stem + ".c")
h_path = os.path.join(args.outdir, stem + ".h")

h = []
h.append("// Auto-generated by tools/gen_glyphfont.py -- do not edit by hand.")
h.append("#pragma once")
h.append("")
h.append('#include "glyphfont.h"')
h.append("")
h.append("#define %s_COUNT %d" % (stem.upper(), len(glyphs)))
h.append("")
h.append("extern const glyph_t %s_glyphs[%s_COUNT];" % (stem, stem.upper()))
h.append("extern const uint8_t %s_data[];" % stem)
with open(h_path, "w", encoding="utf-8") as f:
    f.write("\n".join(h) + "\n")

c = []
c.append("// Auto-generated by tools/gen_glyphfont.py -- do not edit by hand.")
c.append("// %s, %s at %d px, threshold %d." %
         (os.path.basename(args.ttf), stem, args.size, args.threshold))
c.append("")
c.append('#include "%s.h"' % stem)
c.append("")
c.append("const uint8_t %s_data[] = {" % stem)
for i in range(0, len(data), 16):
    c.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
c.append("};")
c.append("")
c.append("const glyph_t %s_glyphs[%s_COUNT] = {" % (stem, stem.upper()))
for cp, width, advance, row_bytes, rows, offset in glyphs:
    c.append("    { 0x%04X, %d, %d, %d, %d, %d }," %
             (cp, offset, width, advance, row_bytes, rows))
c.append("};")
with open(c_path, "w", encoding="utf-8") as f:
    f.write("\n".join(c) + "\n")

print("wrote %s (%d glyphs, %d bytes of bitmaps)" % (c_path, len(glyphs), len(data)))
