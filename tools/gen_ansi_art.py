#!/usr/bin/env python3
"""Turn ANSI colour art files into 1-bit bitmaps for the e-paper clock.

Each file has one character per cell, prefixed with a foreground colour escape.
Both 24-bit (`ESC[38;2;R;G;Bm`) and xterm-256 (`ESC[38;5;Nm`) colours are
understood. Luminance is mapped to three levels:
  dark    -> solid ink
  middle  -> 2x2 checkerboard (light grey on the panel)
  bright  -> paper white
which keeps the shape readable on a black/white panel without a greyscale
driver.

Several files can be converted at once; the output is one table that the
firmware rotates through.

Usage:
    python3 tools/gen_ansi_art.py ../ANSI/ansi.txt \
        --name ansi_art
    python3 tools/gen_ansi_art.py ../ANSI/ansi.txt ../ANSI/laugh.txt \
        ../ANSI/love.txt ../ANSI/speechless.txt --name ansi_art
    python3 tools/gen_ansi_art.py ../ANSI/laugh.txt --preview
"""

import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

ap = argparse.ArgumentParser()
ap.add_argument("inputs", nargs="+")
ap.add_argument("--name", default="ansi_art")
ap.add_argument("--outdir", default=os.path.join(ROOT, "main"))
ap.add_argument("--dark", type=float, default=110.0,
                help="luminance below this is solid ink")
ap.add_argument("--bright", type=float, default=245.0,
                help="luminance above this is paper white")
ap.add_argument("--preview", action="store_true")
args = ap.parse_args()

cell = re.compile(
    r"\x1b\[(?:38;2;(\d+);(\d+);(\d+)|38;5;(\d+))m(.)")

# The first 16 xterm colours. Only used when an art file references them.
BASE16 = [
    (0, 0, 0), (128, 0, 0), (0, 128, 0), (128, 128, 0),
    (0, 0, 128), (128, 0, 128), (0, 128, 128), (192, 192, 192),
    (128, 128, 128), (255, 0, 0), (0, 255, 0), (255, 255, 0),
    (0, 0, 255), (255, 0, 255), (0, 255, 255), (255, 255, 255),
]

CUBE = [0, 95, 135, 175, 215, 255]


def xterm256(index):
    if index < 16:
        return BASE16[index]
    if index < 232:
        index -= 16
        return (CUBE[index // 36], CUBE[(index % 36) // 6], CUBE[index % 6])
    value = 8 + (index - 232) * 10
    return (value, value, value)


def lum(r, g, b):
    return 0.299 * r + 0.587 * g + 0.114 * b


def parse(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    rows = []
    for line in text.split("\n"):
        cells = cell.findall(line)
        if not cells:
            continue
        rows.append(cells)

    rows = rows[:64]          # keep the table small
    width = max((len(row) for row in rows), default=0)
    height = len(rows)

    art = []
    for y, row in enumerate(rows):
        line = []
        for x in range(width):
            if x >= len(row):
                line.append(0)
                continue
            r24, g24, b24, idx, _ch = row[x]
            if r24 != "":
                r, g, b = int(r24), int(g24), int(b24)
            else:
                r, g, b = xterm256(int(idx))
            value = lum(r, g, b)
            if value < args.dark:
                ink = 1
            elif value < args.bright:
                ink = 1 if ((x + y) & 1) == 0 else 0
            else:
                ink = 0
            line.append(ink)
        art.append(line)
    return art, width, height


def pack(art, width):
    row_bytes = (width + 7) // 8
    data = bytearray()
    for line in art:
        packed = bytearray(row_bytes)
        for x, ink in enumerate(line):
            if ink:
                packed[x >> 3] |= 0x80 >> (x & 7)
        data.extend(packed)
    return data, row_bytes


def main():
    if args.preview:
        for path in args.inputs:
            art, width, height = parse(path)
            print("== %s (%dx%d)" % (os.path.basename(path), width, height))
            for y, line in enumerate(art):
                print("%2d|%s|" % (y, "".join("#" if v else " " for v in line)))
        return

    arts = []
    for path in args.inputs:
        art, width, height = parse(path)
        data, row_bytes = pack(art, width)
        arts.append((os.path.basename(path), width, height, row_bytes, data))

    stem = args.name
    h_path = os.path.join(args.outdir, stem + ".h")
    c_path = os.path.join(args.outdir, stem + ".c")

    with open(h_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/gen_ansi_art.py -- do not edit by hand.\n")
        f.write("#pragma once\n\n#include <stdint.h>\n\n")
        f.write("/* One 1-bit thumbnail. 1 = ink, rows are MSB first. */\n")
        f.write("typedef struct {\n")
        f.write("    const uint8_t *data;\n")
        f.write("    uint16_t width;\n")
        f.write("    uint16_t height;\n")
        f.write("    uint8_t row_bytes;\n")
        f.write("} ansi_art_t;\n\n")
        f.write("#define ANSI_ART_COUNT %d\n\n" % len(arts))
        f.write("extern const ansi_art_t ansi_arts[ANSI_ART_COUNT];\n")

    with open(c_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/gen_ansi_art.py -- do not edit by hand.\n\n")
        f.write("#include \"%s.h\"\n\n" % stem)
        for n, (name, width, height, row_bytes, data) in enumerate(arts):
            f.write("// %s (%dx%d cells, %d bytes)\n" % (name, width, height, len(data)))
            f.write("static const uint8_t art_%d[] = {\n" % n)
            for i in range(0, len(data), row_bytes):
                chunk = data[i:i + row_bytes]
                f.write("    " + ", ".join("0x%02X" % b for b in chunk) + ",\n")
            f.write("};\n\n")
        f.write("const ansi_art_t ansi_arts[ANSI_ART_COUNT] = {\n")
        for n, (name, width, height, row_bytes, data) in enumerate(arts):
            f.write("    { art_%d, %d, %d, %d },  // %s\n" %
                    (n, width, height, row_bytes, name))
        f.write("};\n")

    print("wrote %s (%d arts: %s)" %
          (c_path, len(arts), ", ".join(a[0] for a in arts)))


main()
