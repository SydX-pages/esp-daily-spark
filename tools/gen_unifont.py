#!/usr/bin/env python3
"""Generate a 1-bit bitmap font from the bundled GNU Unifont hex file.

Unifont needs no font rasteriser (no PIL), which makes this usable in a plain
Python environment: each line of the .hex file is either

    XXXX:HHHH...   (8x16 glyph, 32 hex digits = 16 bytes)
    XXXX:HH...     (16x16 glyph, 64 hex digits = 32 bytes)

Usage:
    python3 tools/gen_unifont.py --name font_bar \
        --chars "0123456789: 年月日星期一二三四五六"

Outputs main/<name>.c and main/<name>.h in the glyphfont table format.
"""

import argparse
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
HEX = os.path.join(HERE, "fonts", "unifont.hex.gz")

ap = argparse.ArgumentParser()
ap.add_argument("--name", required=True)
ap.add_argument("--hex", default=HEX)
ap.add_argument("--range", help="inclusive code point range, e.g. 0x20-0x7e")
ap.add_argument("--chars")
ap.add_argument("--chars-file",
                help="UTF-8 text file whose characters are all included")
ap.add_argument("--advance", type=int, default=0,
                help="extra pixels added to each glyph advance (default 0)")
ap.add_argument("--outdir", default=os.path.join(ROOT, "main"))
args = ap.parse_args()

if sum(1 for x in (args.range, args.chars, args.chars_file) if x) != 1:
    raise SystemExit("use exactly one of --range, --chars or --chars-file")

if args.range:
    lo, hi = args.range.split("-")
    wanted = set(range(int(lo, 0), int(hi, 0) + 1))
elif args.chars_file:
    with open(args.chars_file, encoding="utf-8") as f:
        wanted = {ord(c) for c in f.read() if not c.isspace()}
else:
    wanted = {ord(c) for c in args.chars}

glyphs = []
with gzip.open(args.hex, "rt", encoding="ascii") as f:
    for line in f:
        cp_s, _, hex_s = line.strip().partition(":")
        if not cp_s:
            continue
        cp = int(cp_s, 16)
        if cp not in wanted:
            continue
        raw = bytes.fromhex(hex_s)
        if len(raw) == 16:
            rows, row_bytes = 16, 1
        elif len(raw) == 32:
            rows, row_bytes = 16, 2
        else:
            continue
        glyphs.append((cp, row_bytes, raw))

glyphs.sort(key=lambda g: g[0])
if not glyphs:
    raise SystemExit("no glyphs found")

WANTED_UNUSED = wanted - {g[0] for g in glyphs}
if WANTED_UNUSED:
    print("missing:", "".join(sorted(chr(c) for c in WANTED_UNUSED))[:40])

data = bytearray()
table = []
for cp, row_bytes, raw in glyphs:
    table.append((cp, len(data) // 1, row_bytes * 8, row_bytes * 8 + args.advance,
                  row_bytes, 16))
    data.extend(raw)

stem = args.name
h_path = os.path.join(args.outdir, stem + ".h")
c_path = os.path.join(args.outdir, stem + ".c")

with open(h_path, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/gen_unifont.py -- do not edit by hand.\n")
    f.write("#pragma once\n\n#include \"glyphfont.h\"\n\n")
    f.write("#define %s_COUNT %d\n\n" % (stem.upper(), len(table)))
    f.write("extern const glyph_t %s_glyphs[%s_COUNT];\n" % (stem, stem.upper()))
    f.write("extern const uint8_t %s_data[];\n" % stem)

with open(c_path, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/gen_unifont.py -- do not edit by hand.\n")
    f.write("// GNU Unifont, 8x16 / 16x16, 1 = ink.\n\n")
    f.write("#include \"%s.h\"\n\n" % stem)
    f.write("const glyph_t %s_glyphs[%s_COUNT] = {\n" % (stem, stem.upper()))
    for cp, off, w, adv, rb, rows in table:
        f.write("    { 0x%04X, %6d, %3d, %3d, %2d, %2d },\n"
                % (cp, off, w, adv, rb, rows))
    f.write("};\n\n")
    f.write("const uint8_t %s_data[] = {\n" % stem)
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        f.write("    " + ", ".join("0x%02X" % b for b in chunk) + ",\n")
    f.write("};\n")

print("wrote %s (%d glyphs, %d bytes)" % (c_path, len(table), len(data)))
